// `deno task types`: the agent contract's types, generated from the fleet
// binary's own `fleet agent schema`, into contract.json (the schema as fleet
// printed it, byte for byte) and contract.d.ts (its types, for the adapter's
// code). Both are committed, and CI reruns this and diffs them: a hand-edited
// type is a defect.
//
// THE FLEET IS $FLEET_BIN, else the `fleet` on PATH. Run it against the fleet
// the pack is measured against, because the schema is that binary's contract.
//
// A HAND-ROLLED EMITTER and not json-schema-to-typescript: the schema uses a
// dozen keywords (below), the emitter is one screen, it needs no network to
// run in CI, and a keyword it has never met stops it — so a contract that
// grows a keyword is read by a person before any type moves. The validator
// the adapter checks requests with (lib/schema.ts) reads the same keywords.
//
// THE BD PACK'S EMITTER, reused (adapters/store/bd/.../scripts/types.ts at
// fleet-packs 37d01bc): fleet builds both contracts' documents with one
// generator (core/src/schema.rs), so one emitter reads both. The agent
// contract adds one shape the store's never had, a map (`object` below). A
// pack installs alone, so each carries its own copy.

import { KEYWORDS } from "../lib/schema.ts";

// lib/schema.ts reads no contract of its own, so this script runs where
// contract.json is not written yet.

type Schema = { [key: string]: unknown } | boolean;

const HEADER =
  `// GENERATED by \`deno task types\` (scripts/types.ts) from \`fleet agent schema\`.
// Do not edit by hand: rerun the task against the pinned fleet, and read its
// diff as the contract's change.
//`;

/** A name TypeScript takes bare as a property key. */
const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function key(name: string): string {
  return IDENTIFIER.test(name) ? name : JSON.stringify(name);
}

/** `order.set` as `OrderSet`, `holds.open` as `HoldsOpen`. */
function pascal(verb: string): string {
  return verb.split(/[._]/).map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");
}

function refName(ref: string): string {
  const prefix = "#/$defs/";
  if (!ref.startsWith(prefix)) {
    throw new Error(`a $ref outside $defs: ${ref}`);
  }
  return ref.slice(prefix.length);
}

/** The doc lines a schema's own constraints and description make. */
function doc(schema: Schema): string[] {
  if (typeof schema !== "object") return [];
  const lines: string[] = [];
  if (typeof schema.description === "string") lines.push(schema.description);
  if (typeof schema.pattern === "string") {
    lines.push(`Pattern: \`${schema.pattern}\``);
  }
  if (typeof schema.format === "string") lines.push(`Format: ${schema.format}`);
  if (schema.minimum !== undefined) lines.push(`Minimum: ${schema.minimum}`);
  if (schema.maximum !== undefined) lines.push(`Maximum: ${schema.maximum}`);
  if (schema.default !== undefined) {
    lines.push(`Default: \`${JSON.stringify(schema.default)}\``);
  }
  return lines;
}

function comment(lines: string[], indent: string): string {
  if (lines.length === 0) return "";
  return `${indent}/**\n${
    lines.map((line) => `${indent} * ${line}`).join("\n")
  }\n${indent} */\n`;
}

function union(members: string[]): string {
  const unique = [...new Set(members)];
  return unique.length === 1 ? unique[0] : unique.map(paren).join(" | ");
}

/** A member of a union or an array's element, bracketed where it is itself a union. */
function paren(type: string): string {
  return /^[^{]*\|/.test(type) ? `(${type})` : type;
}

function emit(schema: Schema, indent = ""): string {
  if (schema === true) return "unknown";
  if (schema === false) return "never";
  const unknown = Object.keys(schema).filter((word) => !KEYWORDS.has(word));
  if (unknown.length > 0) {
    throw new Error(
      `the schema uses ${
        unknown.join(", ")
      }, which this emitter has never met: ${JSON.stringify(schema)}`,
    );
  }
  if (typeof schema.$ref === "string") return refName(schema.$ref);
  if ("const" in schema) return JSON.stringify(schema.const);
  if (Array.isArray(schema.enum)) {
    return union(schema.enum.map((value) => JSON.stringify(value)));
  }
  for (const word of ["oneOf", "anyOf"] as const) {
    const members = schema[word];
    if (Array.isArray(members)) {
      if (schema.properties !== undefined || schema.type !== undefined) {
        throw new Error(
          `${word} beside a type or properties: ${JSON.stringify(schema)}`,
        );
      }
      return union(members.map((member) => emit(member as Schema, indent)));
    }
  }
  const types = schema.type === undefined
    ? (schema.properties !== undefined ? ["object"] : [])
    : Array.isArray(schema.type)
    ? schema.type
    : [schema.type];
  if (types.length === 0) return "unknown";
  return union(types.map((type) => {
    switch (type) {
      case "string":
        return "string";
      case "integer":
      case "number":
        return "number";
      case "boolean":
        return "boolean";
      case "null":
        return "null";
      case "array":
        return schema.items === undefined
          ? "unknown[]"
          : `${paren(emit(schema.items as Schema, indent))}[]`;
      case "object":
        return object(schema, indent);
      default:
        throw new Error(`a type this emitter has never met: ${type}`);
    }
  }));
}

/**
 * An object's named keys. An object without `additionalProperties: false`
 * accepts keys it does not name, and its type names only the ones it does:
 * an index signature would let a misspelt key through every read.
 *
 * A MAP is the one exception: an object naming no key whose
 * `additionalProperties` is a schema — launch's `env`, whose every key is a
 * variable and every value a string — is an index signature over that
 * schema's type. One that names keys as well is a shape this emitter has
 * never met, and stops it.
 */
function object(schema: { [key: string]: unknown }, indent: string): string {
  const values = schema.additionalProperties;
  if (typeof values === "object" && values !== null) {
    if (schema.properties !== undefined) {
      throw new Error(
        `named keys beside a map's values: ${JSON.stringify(schema)}`,
      );
    }
    return `{ [key: string]: ${emit(values as Schema, indent)} }`;
  }
  const properties = (schema.properties ?? {}) as { [key: string]: Schema };
  const required = new Set((schema.required ?? []) as string[]);
  const inner = `${indent}  `;
  const lines = Object.entries(properties).map(([name, property]) =>
    `${comment(doc(property), inner)}${inner}${key(name)}${
      required.has(name) ? "" : "?"
    }: ${emit(property, inner)};`
  );
  if (lines.length === 0) return "Record<string, never>";
  return `{\n${lines.join("\n")}\n${indent}}`;
}

async function sha256(text: string): Promise<string> {
  const digest = await crypto.subtle.digest(
    "SHA-256",
    new TextEncoder().encode(text),
  );
  return [...new Uint8Array(digest)].map((b) => b.toString(16).padStart(2, "0"))
    .join("");
}

/** The whole of contract.d.ts for one schema document's text. */
export async function generate(text: string): Promise<string> {
  const document = JSON.parse(text) as {
    schema_version: number;
    $defs: { [name: string]: Schema };
    verbs: { [verb: string]: { request: Schema; response: Schema } };
    refusal: Schema;
    error: Schema;
  };
  const out: string[] = [
    HEADER,
    `// schema_version: ${document.schema_version}`,
    `// contract.json sha256: ${await sha256(text)}`,
    "",
    "/** The contract's version, which every request and answer carries. */",
    `export type SchemaVersion = ${document.schema_version};`,
    "",
  ];
  for (const [name, schema] of Object.entries(document.$defs)) {
    out.push(
      `${comment(doc(schema), "")}export type ${name} = ${emit(schema)};`,
    );
    out.push("");
  }
  const verbs = Object.keys(document.verbs);
  for (const verb of verbs) {
    const { request, response } = document.verbs[verb];
    out.push(`/** \`${verb}\`'s request. */`);
    out.push(`export type ${pascal(verb)}Request = ${emit(request)};`);
    out.push("");
    out.push(`/** \`${verb}\`'s answer, exit 0. */`);
    out.push(`export type ${pascal(verb)}Response = ${emit(response)};`);
    out.push("");
  }
  out.push("/** Exit 1's answer: the record's refusal. */");
  out.push(`export type RefusalAnswer = ${emit(document.refusal)};`);
  out.push("");
  out.push("/** Exit 3's answer: what could not be told. */");
  out.push(`export type ErrorAnswer = ${emit(document.error)};`);
  out.push("");
  out.push(
    "/** Every verb, by the name it is called by, with its two shapes. */",
  );
  out.push("export type Verbs = {");
  for (const verb of verbs) {
    out.push(
      `  ${key(verb)}: { request: ${pascal(verb)}Request; response: ${
        pascal(verb)
      }Response };`,
    );
  }
  out.push("};");
  out.push("");
  out.push("export type Verb = keyof Verbs;");
  return out.join("\n") + "\n";
}

async function schemaText(): Promise<string> {
  const fleet = Deno.env.get("FLEET_BIN") || "fleet";
  const out = await new Deno.Command(fleet, {
    args: ["agent", "schema"],
    stdout: "piped",
    stderr: "inherit",
  }).output();
  if (!out.success) {
    throw new Error(`\`${fleet} agent schema\` exited ${out.code}`);
  }
  return new TextDecoder().decode(out.stdout);
}

if (import.meta.main) {
  const text = await schemaText();
  await Deno.writeTextFile(new URL("../contract.json", import.meta.url), text);
  await Deno.writeTextFile(
    new URL("../contract.d.ts", import.meta.url),
    await generate(text),
  );
}
